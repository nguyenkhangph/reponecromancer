import type { ConfigFinding, FileMap } from "./types";

export interface ConfigOutcome {
  findings: ConfigFinding[];
  deletes: string[];
  adds: FileMap;
  scripts: Record<string, string>;
  /** dependencies migrated from bower.json */
  bowerDeps: Record<string, string>;
  introducedDev: string[];
  reasons: Record<string, string[]>;
}

function stripJsonComments(s: string): string {
  return s.replace(/\/\*[\s\S]*?\*\//g, "").replace(/(^|[^:"'])\/\/.*$/gm, "$1");
}

const BROWSER_GLOBALS = ["window", "document", "navigator", "location", "history", "localStorage", "sessionStorage", "setTimeout", "clearTimeout", "setInterval", "clearInterval", "requestAnimationFrame", "console", "alert", "Event", "CustomEvent", "HTMLElement", "fetch"];
const NODE_GLOBALS = ["require", "module", "exports", "process", "Buffer", "__dirname", "__filename", "console", "setTimeout", "clearTimeout", "setInterval", "clearInterval", "setImmediate", "globalThis", "fetch", "URL", "URLSearchParams", "AbortSignal", "AbortController", "TextEncoder", "TextDecoder", "structuredClone"];

export function eslintFromJshint(jshintrc: string | undefined): string {
  let cfg: any = {};
  try {
    cfg = jshintrc ? JSON.parse(stripJsonComments(jshintrc)) : {};
  } catch {
    cfg = {};
  }
  const globals = new Set<string>();
  if (cfg.browser) BROWSER_GLOBALS.forEach((g) => globals.add(g));
  if (cfg.node || !cfg.browser) NODE_GLOBALS.forEach((g) => globals.add(g));
  if (cfg.jquery) ["$", "jQuery"].forEach((g) => globals.add(g));
  if (cfg.mocha) ["describe", "it", "before", "after", "beforeEach", "afterEach"].forEach((g) => globals.add(g));
  const predef = cfg.predef ?? cfg.globals;
  if (Array.isArray(predef)) predef.forEach((g: string) => globals.add(g.replace(/^-/, "")));
  else if (predef && typeof predef === "object") Object.keys(predef).forEach((g) => globals.add(g));

  const rules: string[] = [];
  if (cfg.eqeqeq) rules.push(`      eqeqeq: "error",`);
  if (cfg.curly) rules.push(`      curly: "error",`);
  if (cfg.undef) rules.push(`      "no-undef": "error",`);
  if (cfg.unused) rules.push(`      "no-unused-vars": "warn",`);
  if (cfg.strict) rules.push(`      strict: ["error", "function"],`);

  const g = [...globals].sort().map((x) => `        ${/^[A-Za-z_$][\w$]*$/.test(x) ? x : JSON.stringify(x)}: "readonly",`).join("\n");
  return `// Generated by RepoNecromancer from .jshintrc — ESLint 9 flat config.
const js = require("@eslint/js");

module.exports = [
  { ignores: ["dist/**", "node_modules/**", "coverage/**", "eslint.config.cjs"] },
  js.configs.recommended,
  {
    files: ["**/*.js", "**/*.cjs"],
    languageOptions: {
      ecmaVersion: 2022,
      sourceType: "script",
      globals: {
${g}
      },
    },
    rules: {
${rules.join("\n")}
    },
  },
  {
    files: ["test/**/*.cjs", "necro-compat/**/*.js"],
    languageOptions: { globals: { require: "readonly", module: "readonly", __dirname: "readonly", process: "readonly", fetch: "readonly", setTimeout: "readonly", clearTimeout: "readonly" } },
    rules: { "no-unused-vars": "off" },
  },
];
`;
}

export const CI_WORKFLOW = `name: CI

on:
  push:
  pull_request:

jobs:
  test:
    runs-on: ubuntu-latest
    strategy:
      matrix:
        node: [20, 22]
    steps:
      - uses: actions/checkout@v4
      - uses: actions/setup-node@v4
        with:
          node-version: \${{ matrix.node }}
      - run: npm install --no-audit --no-fund
      - run: npm test
`;

export function analyzeConfigs(files: FileMap, pkg: any): ConfigOutcome {
  const out: ConfigOutcome = { findings: [], deletes: [], adds: {}, scripts: {}, bowerDeps: {}, introducedDev: [], reasons: {} };
  const reason = (file: string, r: string) => (out.reasons[file] ??= []).push(r);
  const has = (p: string) => Object.prototype.hasOwnProperty.call(files, p);

  if (has(".travis.yml")) {
    const travis = files[".travis.yml"];
    const nodes = [...travis.matchAll(/["']?(\d+(?:\.\d+)?|iojs|node)["']?\s*$/gm)].map((m) => m[1]).slice(0, 4);
    out.findings.push({
      id: "travis-ci",
      file: ".travis.yml",
      title: "Travis CI config",
      severity: "critical",
      cause: `travis-ci.org shut down in 2021${nodes.length ? `; targets Node ${nodes.join(", ")}` : ""}. CI has been silently dead.`,
      remedy: "Replace with a GitHub Actions workflow on Node 20/22.",
    });
    out.deletes.push(".travis.yml");
    out.adds[".github/workflows/ci.yml"] = CI_WORKFLOW;
    reason(".travis.yml", "travis-ci.org is gone");
    reason(".github/workflows/ci.yml", "Replaces Travis CI (Node 20 + 22 matrix)");
  } else if (!Object.keys(files).some((f) => f.startsWith(".github/workflows/"))) {
    out.findings.push({ id: "no-ci", file: "(none)", title: "No CI", severity: "info", cause: "Nothing verifies this repo on push.", remedy: "Add a GitHub Actions workflow." });
    out.adds[".github/workflows/ci.yml"] = CI_WORKFLOW;
    reason(".github/workflows/ci.yml", "Adds CI on Node 20 + 22");
  }

  if (has("bower.json")) {
    let bower: any = {};
    try {
      bower = JSON.parse(files["bower.json"]);
    } catch {}
    const deps = { ...(bower.dependencies ?? {}) };
    out.bowerDeps = deps;
    out.findings.push({
      id: "bower",
      file: "bower.json",
      title: "Bower package manifest",
      severity: "critical",
      cause: "Bower is deprecated and its registry is read-only; front-end deps must come from npm.",
      remedy: `Move ${Object.keys(deps).join(", ") || "dependencies"} into package.json.`,
    });
    out.deletes.push("bower.json");
    reason("bower.json", "Dependencies moved to package.json");
    if (has(".bowerrc")) out.deletes.push(".bowerrc");
  }

  const gruntfile = has("Gruntfile.js") ? "Gruntfile.js" : has("Gruntfile.coffee") ? "Gruntfile.coffee" : null;
  if (gruntfile) {
    const g = files[gruntfile];
    const tasks: string[] = [];
    if (/jshint/.test(g)) {
      out.scripts.lint = "eslint .";
      out.introducedDev.push("eslint", "@eslint/js");
      tasks.push("jshint → `npm run lint` (ESLint)");
    }
    const builds = [...g.matchAll(/['"]([^'"]+\.min\.js)['"]\s*:\s*\[?\s*['"]([^'"]+\.js)['"]/g)];
    if (builds.length) {
      out.scripts.build = builds.map((m) => `esbuild ${m[2]} --minify --outfile=${m[1]}`).join(" && ");
      out.introducedDev.push("esbuild");
      tasks.push("uglify → `npm run build` (esbuild)");
    }
    if (/qunit/.test(g)) tasks.push("qunit (PhantomJS) → generated node:test suite");
    out.findings.push({
      id: "grunt",
      file: gruntfile,
      title: "Grunt build pipeline",
      severity: "critical",
      cause: "Grunt 0.4 plugins are unmaintained; grunt-contrib-qunit pulls PhantomJS which no longer installs.",
      remedy: tasks.length ? tasks.join("; ") : "Replace with npm scripts.",
    });
    out.deletes.push(gruntfile);
    reason(gruntfile, "Replaced by npm scripts");
  }

  if (has(".jshintrc")) {
    out.findings.push({
      id: "jshint",
      file: ".jshintrc",
      title: "JSHint config",
      severity: "warning",
      cause: "JSHint does not understand modern syntax and is superseded by ESLint.",
      remedy: "Translate options and globals into an ESLint 9 flat config.",
    });
    out.deletes.push(".jshintrc");
    if (has(".jshintignore")) out.deletes.push(".jshintignore");
    out.adds["eslint.config.cjs"] = eslintFromJshint(files[".jshintrc"]);
    out.scripts.lint = "eslint .";
    out.introducedDev.push("eslint", "@eslint/js");
    reason(".jshintrc", "Translated to eslint.config.cjs");
    reason("eslint.config.cjs", "Translated from .jshintrc (globals + rules)");
  }

  if (has("gulpfile.js")) {
    out.findings.push({
      id: "gulp",
      file: "gulpfile.js",
      title: "Gulp build",
      severity: "warning",
      cause: "Gulp 3 crashes on Node 12+ with `ReferenceError: primordials is not defined`.",
      remedy: "Upgrade gulp to v5 (gulp.series/parallel) or replace with npm scripts.",
    });
  }

  const enginesNode: string | undefined = pkg?.engines?.node;
  if (enginesNode && /^\D*0\.|^\D*([1-9]|1[0-7])(\D|$)/.test(enginesNode)) {
    out.findings.push({
      id: "engines",
      file: "package.json",
      title: `engines.node "${enginesNode}"`,
      severity: "critical",
      cause: "Pinned to a Node.js release that reached end-of-life years ago.",
      remedy: 'Set engines.node to ">=20".',
    });
  }

  if (!has(".nvmrc")) {
    out.adds[".nvmrc"] = "22\n";
    reason(".nvmrc", "Pins the resurrected runtime to Node 22 LTS");
  }

  if (!Object.keys(files).some((f) => /^(package-lock\.json|yarn\.lock|pnpm-lock\.yaml|npm-shrinkwrap\.json)$/.test(f))) {
    out.findings.push({
      id: "no-lockfile",
      file: "(none)",
      title: "No lockfile",
      severity: "info",
      cause: "Installs are not reproducible; the dependency tree drifts on every install.",
      remedy: "Commit the package-lock.json generated by the first `npm install`.",
    });
  }

  if (!Object.keys(files).some((f) => /^(LICEN[CS]E|COPYING)(\.|$)/i.test(f)) && !pkg?.license) {
    out.findings.push({ id: "no-license", file: "(none)", title: "No license", severity: "info", cause: "Nobody can legally reuse the resurrected code.", remedy: "Add an OSI license (MIT/Apache-2.0)." });
  }

  return out;
}
