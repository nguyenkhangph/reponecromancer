import { applyCodemods, RULES } from "./codemods";
import { analyzeConfigs } from "./configs";
import { auditDependencies } from "./deps";
import { generateTests, TEST_DIR } from "./testgen";
import type { CodeFinding, FileMap, FilePatch, NecropsyReport, PlanStep, RegistryLookup, Severity } from "./types";

export * from "./types";
export { npmRegistry, snapshotRegistry } from "./registry";
export { RULES } from "./codemods";

export const ENGINE_VERSION = "0.1.0";

export class NotANodeProjectError extends Error {
  constructor() {
    super("No package.json at the repository root — RepoNecromancer currently raises JavaScript/Node.js projects.");
  }
}

const PENALTY: Record<Severity, number> = { fatal: 16, critical: 7, warning: 3, info: 1 };
const SEV_RANK: Record<Severity, number> = { fatal: 0, critical: 1, warning: 2, info: 3 };

export function isScannable(path: string): boolean {
  return /\.(c?js|mjs)$/.test(path) && !/(^|\/)(node_modules|bower_components|dist|vendor|coverage)\//.test(path) && !/\.min\.js$/.test(path);
}

export interface ResurrectOptions {
  registry: RegistryLookup;
  now?: Date;
}

export async function resurrect(files: FileMap, opts: ResurrectOptions): Promise<NecropsyReport> {
  const warnings: string[] = [];
  if (files["package.json"] === undefined) throw new NotANodeProjectError();
  let pkg: any;
  try {
    pkg = JSON.parse(files["package.json"]);
  } catch {
    throw new Error("package.json is not valid JSON.");
  }

  // 1. Exhume: config fossils
  const configs = analyzeConfigs(files, pkg);

  // 2. Suture: AST codemods over every scannable source file
  const after: FileMap = { ...files };
  const patches: FilePatch[] = [];
  const code: CodeFinding[] = [];
  const migrated = new Set<string>();
  const stuck = new Set<string>();
  const introduced = new Set<string>();
  const scannable = Object.keys(files).filter(isScannable).sort();
  for (const f of scannable) {
    const r = applyCodemods(f, files[f], files);
    code.push(...r.findings);
    r.migrated.forEach((m) => migrated.add(m));
    r.stuck.forEach((m) => stuck.add(m));
    r.introduced.forEach((m) => introduced.add(m));
    for (const [p, c] of Object.entries(r.addFiles)) {
      if (after[p] === undefined) {
        after[p] = c;
        patches.push({ path: p, kind: "added", before: null, after: c, reasons: [`Compat shim generated by request-to-fetch-shim`] });
      }
    }
    if (r.changed) {
      after[f] = r.code;
      const reasons = [...new Set(r.findings.filter((x) => x.fixed).map((x) => RULES[x.rule]?.title ?? x.rule))];
      patches.push({ path: f, kind: "modified", before: files[f], after: r.code, reasons });
    }
  }
  for (const m of stuck) migrated.delete(m);

  const hasLegacySuite = Object.keys(files).some((f) => /(^|\/)(test|tests|spec)\/.+\.(c?js)$/.test(f) && /\b(describe|it)\(/.test(files[f]));

  // 3. Transplant: dependency audit + new package.json
  const deps = await auditDependencies(pkg, opts.registry, {
    migrated,
    stuck,
    introduced,
    introducedDev: new Set(configs.introducedDev),
    bowerDeps: configs.bowerDeps,
    keepTestRunner: hasLegacySuite,
  });

  // 4. Galvanize: regression tests generated from the resurrected tree
  const tests = generateTests(after, pkg);
  const testPaths = tests.map((t) => t.path);

  const nextPkg: any = { ...pkg };
  nextPkg.engines = { ...(pkg.engines ?? {}), node: ">=20" };
  const scripts: Record<string, string> = { ...(pkg.scripts ?? {}) };
  const necroTest = testPaths.length ? `node --test ${testPaths.join(" ")}` : null;
  if (necroTest) {
    if (hasLegacySuite && scripts.test && !/no test specified/.test(scripts.test)) scripts.test = `${scripts.test} && ${necroTest}`;
    else scripts.test = necroTest;
  }
  for (const [k, v] of Object.entries(configs.scripts)) scripts[k] = v;
  for (const k of Object.keys(scripts)) if (/\b(grunt|bower)\b/.test(scripts[k]) && !configs.scripts[k]) delete scripts[k];
  if (pkg.scripts?.postinstall && /bower/.test(pkg.scripts.postinstall)) delete scripts.postinstall;
  nextPkg.scripts = scripts;
  nextPkg.dependencies = deps.dependencies;
  if (Object.keys(deps.devDependencies).length) nextPkg.devDependencies = deps.devDependencies;
  else delete nextPkg.devDependencies;
  if (!Object.keys(nextPkg.dependencies).length) delete nextPkg.dependencies;
  if (!nextPkg.license) nextPkg.license = "MIT";
  const pkgAfter = JSON.stringify(nextPkg, null, 2) + "\n";
  patches.unshift({
    path: "package.json",
    kind: "modified",
    before: files["package.json"],
    after: pkgAfter,
    reasons: [
      `engines.node → ">=20"`,
      ...deps.findings.filter((d) => d.action.type !== "keep").map((d) => `${d.name}: ${d.action.type}${d.action.to ? " → " + d.action.to : ""}${d.action.range ? " " + d.action.range : ""}`),
      ...deps.added.map((a) => `+ ${a.name} ${a.range} (${a.reason})`),
      necroTest ? "test script → generated node:test suite" : "",
    ].filter(Boolean),
  });
  after["package.json"] = pkgAfter;

  for (const p of configs.deletes) {
    if (files[p] === undefined) continue;
    patches.push({ path: p, kind: "deleted", before: files[p], after: null, reasons: configs.reasons[p] ?? [] });
    delete after[p];
  }
  for (const [p, c] of Object.entries(configs.adds)) {
    if (files[p] !== undefined) continue;
    patches.push({ path: p, kind: "added", before: null, after: c, reasons: configs.reasons[p] ?? [] });
  }
  for (const t of tests) {
    patches.push({ path: t.path, kind: "added", before: null, after: t.content, reasons: [`${t.cases} ${t.strategy} case${t.cases === 1 ? "" : "s"}`] });
  }

  // 5. Plan
  const plan: PlanStep[] = [
    {
      phase: "exhume",
      title: "Exhume config fossils",
      items: configs.findings.filter((c) => c.severity !== "info" || c.id === "no-ci").map((c) => `${c.title}: ${c.remedy}`),
    },
    {
      phase: "transplant",
      title: "Transplant dependencies",
      items: [
        ...deps.findings.filter((d) => d.action.type !== "keep").map((d) => `${d.name}@${d.declared} → ${d.action.type === "remove" ? "removed" : d.action.type === "replace" ? `${d.action.to}@${d.action.range}` : `${d.name}@${d.action.range}`} — ${d.action.reason}`),
        ...deps.added.map((a) => `+ ${a.name}@${a.range} — ${a.reason}`),
      ],
    },
    {
      phase: "suture",
      title: "Suture breaking changes (AST codemods)",
      items: Object.entries(
        code.reduce<Record<string, { fixed: number; open: number }>>((acc, f) => {
          const k = RULES[f.rule]?.title ?? f.rule;
          acc[k] ??= { fixed: 0, open: 0 };
          f.fixed ? acc[k].fixed++ : acc[k].open++;
          return acc;
        }, {}),
      ).map(([k, v]) => `${k} — ${v.fixed} patched${v.open ? `, ${v.open} flagged for review` : ""}`),
    },
    {
      phase: "galvanize",
      title: "Galvanize regression tests",
      items: tests.map((t) => `${t.path}: ${t.cases} ${t.strategy} case${t.cases === 1 ? "" : "s"}`),
    },
    {
      phase: "verify",
      title: "Verify pulse",
      items: [`npm install on Node 20/22`, necroTest ? `npm test → ${necroTest}` : "npm test", configs.scripts.lint ? "npm run lint" : "", configs.scripts.build ? "npm run build" : ""].filter(Boolean),
    },
  ];

  // 6. Vitals
  const allSev: Severity[] = [...deps.findings.filter((d) => d.status !== "healthy" && d.status !== "unknown").map((d) => d.severity), ...configs.findings.map((c) => c.severity), ...code.filter((c) => c.rule !== "callback-to-promise").map((c) => c.severity)];
  const pulse = (sevs: Severity[]) => Math.round(100 * Math.exp(-sevs.reduce((s, v) => s + PENALTY[v], 0) / 140));
  const pulseBefore = Math.max(1, pulse(allSev));
  const openSev: Severity[] = [...code.filter((c) => !c.fixed && c.rule !== "callback-to-promise").map((c) => c.severity), ...deps.findings.filter((d) => d.action.type === "keep" && d.status !== "healthy" && d.status !== "unknown").map((d) => d.severity)];
  const pulseAfter = Math.max(pulseBefore, pulse(openSev));

  const worst = [
    ...code.map((c) => ({ s: c.severity, t: `${c.message} (${c.file}:${c.line})` })),
    ...deps.findings.map((d) => ({ s: d.severity, t: `${d.name}@${d.declared}: ${d.cause}` })),
    ...configs.findings.map((c) => ({ s: c.severity, t: `${c.title}: ${c.cause}` })),
  ].sort((a, b) => SEV_RANK[a.s] - SEV_RANK[b.s])[0];

  const totalLines = scannable.reduce((s, f) => s + files[f].split("\n").length, 0);
  if (!scannable.length) warnings.push("No JavaScript sources found to scan.");

  return {
    engineVersion: ENGINE_VERSION,
    generatedAt: (opts.now ?? new Date()).toISOString(),
    vitals: {
      name: pkg.name ?? "unnamed",
      description: pkg.description ?? null,
      declaredNode: pkg.engines?.node ?? null,
      jsFiles: scannable.length,
      totalLines,
      pulseBefore,
      pulseAfter,
      causeOfDeath: worst?.t ?? "Natural causes (nothing fatal found).",
    },
    deps: deps.findings.sort((a, b) => SEV_RANK[a.severity] - SEV_RANK[b.severity] || a.name.localeCompare(b.name)),
    configs: configs.findings,
    code: code.sort((a, b) => SEV_RANK[a.severity] - SEV_RANK[b.severity] || a.file.localeCompare(b.file) || a.line - b.line),
    plan,
    patches,
    tests,
    warnings,
  };
}

