import type { NecropsyReport, VerifyRecord } from "./types";

const ICON: Record<string, string> = { fatal: "☠️", critical: "🩸", warning: "🕯️", info: "👻" };

/** Markdown necropsy report shipped inside every resurrected tree. */
export function renderNecropsy(r: NecropsyReport, verify?: VerifyRecord | null): string {
  const v = r.vitals;
  const lines: string[] = [];
  lines.push(`# Necropsy report — ${v.name}`, "");
  lines.push(`Generated by [RepoNecromancer](https://github.com/nguyenkhangph/reponecromancer) v${r.engineVersion} on ${r.generatedAt.slice(0, 10)}.`, "");
  lines.push(`| | |`, `|---|---|`);
  lines.push(`| Pulse | **${v.pulseBefore}% → ${v.pulseAfter}%** |`);
  lines.push(`| Declared Node | ${v.declaredNode ?? "—"} → >=20 |`);
  lines.push(`| Sources scanned | ${v.jsFiles} files, ${v.totalLines} lines |`);
  lines.push(`| Cause of death | ${v.causeOfDeath} |`, "");

  lines.push(`## Dependencies`, "", `| Package | Declared | Latest | Status | Action |`, `|---|---|---|---|---|`);
  for (const d of r.deps) {
    const act = d.action.type === "replace" ? `replace → ${d.action.to}@${d.action.range}` : d.action.type === "upgrade" ? `upgrade → ${d.action.range}` : d.action.type;
    lines.push(`| ${ICON[d.severity]} \`${d.name}\` | ${d.declared} | ${d.latest ?? "?"} | ${d.status} | ${act} |`);
  }
  lines.push("");
  if (r.configs.length) {
    lines.push(`## Config fossils`, "");
    for (const c of r.configs) lines.push(`- ${ICON[c.severity]} **${c.title}** (\`${c.file}\`) — ${c.cause} _Remedy:_ ${c.remedy}`);
    lines.push("");
  }
  lines.push(`## Code surgery`, "");
  for (const c of r.code) lines.push(`- ${c.fixed ? "✅" : "⚠️"} \`${c.file}:${c.line}\` ${c.message} — \`${c.snippet.replace(/`/g, "'")}\``);
  lines.push("", `## Migration plan`, "");
  for (const s of r.plan) {
    if (!s.items.length) continue;
    lines.push(`### ${s.title}`, ...s.items.map((i) => `- ${i}`), "");
  }
  lines.push(`## Generated regression tests`, "");
  for (const t of r.tests) lines.push(`- \`${t.path}\` — ${t.cases} ${t.strategy} case${t.cases === 1 ? "" : "s"}`);
  if (verify) {
    lines.push("", `## Verification (${verify.node}, npm ${verify.npm})`, "");
    lines.push(`| | install | tests | checks |`, `|---|---|---|---|`);
    for (const k of ["before", "after"] as const) {
      const run = verify[k];
      lines.push(`| ${k} | ${run.install.ok ? "✅" : "❌"} | ${run.tests.pass}/${run.tests.pass + run.tests.fail} | ${run.checks.map((c) => `${c.name} ${c.ok ? "✅" : "❌"}`).join(" ") || "—"} |`);
    }
  }
  lines.push("", `Next: \`npm install && npm test\``, "");
  return lines.join("\n");
}
